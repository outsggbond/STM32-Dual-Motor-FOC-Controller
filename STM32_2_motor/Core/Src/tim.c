    /* TIM3 clock enable */
    __HAL_RCC_TIM3_CLK_ENABLE();

    /* TIM3 interrupt Init */
    HAL_NVIC_SetPriority(TIM3_IRQn, 0, 0);
    HAL_NVIC_EnableIRQ(TIM3_IRQn);
  /* USER CODE BEGIN TIM3_MspInit 1 */

  /* ★ 控制中断的抢占优先级必须【低于】串口。
     TIM3 与 USART1 原来都配成抢占优先级 0，两者相等 = 谁也不能抢占谁。
     而 TIM3 的 FOC 中断要跑两个电机的 Clarke/Park/SVPWM（Cortex-M3 无 FPU，
     全是软件浮点，调试版 -O0 下长达上百微秒）。这期间到达的串口字节
     无人取走，下一个字节到来时就触发溢出(ORE)，前一个字节被【静默丢弃】。
     实测后果：连发 8 条 STOPALL 有 2 条被截断成"未知子命令"，连发 5 条
     只回 4 条 —— 命令随机损坏，且看不出原因。
     把 TIM3 降到 1，USART1(0) 即可抢占它：串口 ISR 只有几微秒，
     控制环容忍这点抖动，而丢命令不能容忍。
     放在 USER CODE 段里，CubeMX 重新生成代码时不会被覆盖。 */
